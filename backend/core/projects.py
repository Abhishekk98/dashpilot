"""Project workspace on local disk (V1 storage; moves to a database later).

Layout:
    storage/{project_id}/project.json   manifest (name, files, tables)
    storage/{project_id}/files/{file_id}{ext}   original uploads
    storage/{project_id}/profile.json   cached profiling report
    storage/{project_id}/cleaning.json  accepted / skipped cleaning steps
    storage/{project_id}/context.json   business context + brand kit
    storage/{project_id}/brand/logo.*   uploaded logo
    storage/{project_id}/model.json     data-model settings + cached AI table classification
"""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from pathlib import Path

from pydantic import BaseModel, Field


class TableRef(BaseModel):
    name: str
    sheet: str | None = None
    rows: int
    columns: int


class StoredFile(BaseModel):
    id: str
    filename: str
    extension: str
    size_bytes: int
    uploaded_at: datetime
    tables: list[TableRef]


class Project(BaseModel):
    id: str
    name: str
    created_at: datetime
    files: list[StoredFile] = Field(default_factory=list)


class ProjectSummary(BaseModel):
    id: str
    name: str
    created_at: datetime
    updated_at: datetime
    files: list[StoredFile] = Field(default_factory=list)
    files_count: int
    tables_count: int
    rows_total: int
    size_bytes: int
    stage: int  # 1 to 9
    stage_label: str  # e.g., "Ready (.pbip)", "Design Import", "KPIs & DAX", "Data Cleaning", "Upload & Profiling"
    has_build: bool
    build_valid: bool = False
    pages_count: int = 1
    measures_count: int = 0
    industry: str | None = None
    palette_accent: str | None = None


class ProjectNotFoundError(LookupError):
    pass


def _now() -> datetime:
    return datetime.now(timezone.utc)


class ProjectStore:
    def __init__(self, root: Path):
        self.root = Path(root)

    # -- paths -------------------------------------------------------------
    def project_dir(self, project_id: str) -> Path:
        # Ids are generated by us; reject anything that could escape the root.
        if not project_id.isalnum():
            raise ProjectNotFoundError(project_id)
        return self.root / project_id

    def file_path(self, project_id: str, stored: StoredFile) -> Path:
        return self.project_dir(project_id) / "files" / f"{stored.id}{stored.extension}"

    def _manifest(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "project.json"

    def _profile_cache(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "profile.json"

    # -- projects ----------------------------------------------------------
    def create(self, name: str) -> Project:
        project = Project(id=uuid.uuid4().hex, name=name.strip() or "Untitled Project", created_at=_now())
        (self.project_dir(project.id) / "files").mkdir(parents=True, exist_ok=True)
        self.save(project)
        return project

    def get(self, project_id: str) -> Project:
        path = self._manifest(project_id)
        if not path.exists():
            raise ProjectNotFoundError(project_id)
        return Project.model_validate_json(path.read_text(encoding="utf-8"))

    def list(self) -> list[Project]:
        projects: list[Project] = []
        if not self.root.exists():
            return projects
        for path in self.root.iterdir():
            if path.is_dir() and (path / "project.json").exists():
                try:
                    p = Project.model_validate_json((path / "project.json").read_text(encoding="utf-8"))
                    projects.append(p)
                except Exception:
                    continue
        projects.sort(key=lambda p: p.created_at, reverse=True)
        return projects

    def delete(self, project_id: str) -> None:
        p_dir = self.project_dir(project_id)
        if not p_dir.exists():
            raise ProjectNotFoundError(project_id)
        import shutil
        shutil.rmtree(p_dir, ignore_errors=True)

    def summary(self, project: Project) -> ProjectSummary:
        pdir = self.project_dir(project.id)
        files = project.files
        tables_count = sum(len(f.tables) for f in files)
        rows_total = sum(sum(t.rows for t in f.tables) for f in files)
        size_bytes = sum(f.size_bytes for f in files)

        has_build = (pdir / "build" / "build.json").exists()
        has_import = (pdir / "design" / "import.json").exists()
        has_plan = (pdir / "plan.json").exists()
        has_insights = (pdir / "insights.json").exists()
        has_measures = (pdir / "measures.json").exists()
        has_model = (pdir / "model.json").exists()
        has_context = (pdir / "context.json").exists()
        has_cleaning = (pdir / "cleaning.json").exists()

        if has_build:
            stage = 9
            stage_label = "Ready (.pbip)"
        elif has_import:
            stage = 8
            stage_label = "Design Import"
        elif has_plan:
            stage = 7
            stage_label = "Dashboard Plan"
        elif has_insights:
            stage = 6
            stage_label = "AI Insights"
        elif has_measures:
            stage = 5
            stage_label = "KPIs & DAX"
        elif has_model:
            stage = 4
            stage_label = "Data Model"
        elif has_context:
            stage = 3
            stage_label = "Business Context"
        elif has_cleaning:
            stage = 2
            stage_label = "Data Cleaning"
        else:
            stage = 1
            stage_label = "Upload & Profiling"

        build_valid = False
        pages_count = 1
        measures_count = 0
        if has_build:
            try:
                bdata = json.loads((pdir / "build" / "build.json").read_text(encoding="utf-8"))
                build_valid = bdata.get("valid", False)
                pages_count = bdata.get("pages", 1)
                measures_count = bdata.get("measures", 0)
            except Exception:
                pass
        elif has_plan:
            try:
                pdata = json.loads((pdir / "plan.json").read_text(encoding="utf-8"))
                plan_dict = pdata.get("plan", {})
                pages_count = len(plan_dict.get("pages", [1]))
            except Exception:
                pass

        if not measures_count and has_measures:
            try:
                mdata = json.loads((pdir / "measures.json").read_text(encoding="utf-8"))
                measures_count = len(mdata.get("measures", []))
            except Exception:
                pass

        industry = None
        palette_accent = None
        if has_context:
            try:
                cdata = json.loads((pdir / "context.json").read_text(encoding="utf-8"))
                industry = cdata.get("industry")
                palette_accent = cdata.get("palette", {}).get("accent")
            except Exception:
                pass

        updated_at = project.created_at
        try:
            mtimes = [f.stat().st_mtime for f in pdir.glob("*.json")]
            if mtimes:
                updated_at = datetime.fromtimestamp(max(mtimes), tz=timezone.utc)
        except Exception:
            pass

        return ProjectSummary(
            id=project.id,
            name=project.name,
            created_at=project.created_at,
            updated_at=updated_at,
            files=files,
            files_count=len(files),
            tables_count=tables_count,
            rows_total=rows_total,
            size_bytes=size_bytes,
            stage=stage,
            stage_label=stage_label,
            has_build=has_build,
            build_valid=build_valid,
            pages_count=pages_count,
            measures_count=measures_count,
            industry=industry,
            palette_accent=palette_accent,
        )

    def save(self, project: Project) -> None:
        self._manifest(project.id).write_text(project.model_dump_json(indent=2), encoding="utf-8")
        self.clear_profile(project.id)

    # -- files -------------------------------------------------------------
    def add_file(self, project: Project, stored: StoredFile, content: bytes) -> Project:
        self.file_path(project.id, stored).write_bytes(content)
        project.files.append(stored)
        self.save(project)
        return project

    def remove_file(self, project: Project, file_id: str) -> Project:
        stored = next((f for f in project.files if f.id == file_id), None)
        if stored is None:
            raise ProjectNotFoundError(file_id)
        self.file_path(project.id, stored).unlink(missing_ok=True)
        project.files = [f for f in project.files if f.id != file_id]
        self.save(project)
        return project

    # -- profile cache -----------------------------------------------------
    def read_profile(self, project_id: str) -> dict | None:
        path = self._profile_cache(project_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    def write_profile(self, project_id: str, data: dict) -> None:
        self._profile_cache(project_id).write_text(json.dumps(data, default=str), encoding="utf-8")

    def clear_profile(self, project_id: str) -> None:
        self._profile_cache(project_id).unlink(missing_ok=True)

    # -- cleaning decisions ------------------------------------------------
    def _cleaning(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "cleaning.json"

    def read_cleaning(self, project_id: str) -> dict:
        path = self._cleaning(project_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}

    def write_cleaning(self, project_id: str, data: dict) -> None:
        self._cleaning(project_id).write_text(json.dumps(data, indent=2), encoding="utf-8")

    # -- business context & brand ------------------------------------------
    def _context(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "context.json"

    def read_context(self, project_id: str) -> dict | None:
        path = self._context(project_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    def write_context(self, project_id: str, data: dict) -> None:
        self._context(project_id).write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")

    # -- small per-project JSON documents ------------------------------------------
    def read_json(self, project_id: str, filename: str) -> dict:
        path = self.project_dir(project_id) / filename
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}

    def write_json(self, project_id: str, filename: str, data: dict) -> None:
        (self.project_dir(project_id) / filename).write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")

    # -- data model ------------------------------------------------------------
    def _model(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "model.json"

    def read_model(self, project_id: str) -> dict:
        path = self._model(project_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}

    def write_model(self, project_id: str, data: dict) -> None:
        self._model(project_id).write_text(json.dumps(data, indent=2), encoding="utf-8")

    def logo_path(self, project_id: str, extension: str) -> Path:
        return self.project_dir(project_id) / "brand" / f"logo{extension}"

    def save_logo(self, project_id: str, extension: str, content: bytes) -> None:
        self.remove_logo(project_id)
        path = self.logo_path(project_id, extension)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)

    def remove_logo(self, project_id: str) -> None:
        brand = self.project_dir(project_id) / "brand"
        for old in brand.glob("logo.*") if brand.exists() else []:
            old.unlink()


def new_file_id() -> str:
    return uuid.uuid4().hex[:12]
