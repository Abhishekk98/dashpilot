"""Project workspace on local disk (V1 storage; moves to a database later).

Layout:
    storage/{project_id}/project.json   manifest (name, files, tables)
    storage/{project_id}/files/{file_id}{ext}   original uploads
    storage/{project_id}/profile.json   cached profiling report
    storage/{project_id}/cleaning.json  accepted / skipped cleaning steps
    storage/{project_id}/context.json   business context + brand kit
    storage/{project_id}/brand/logo.*   uploaded logo
"""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from pathlib import Path

from pydantic import BaseModel, Field


class TableRef(BaseModel):
    name: str
    sheet: str | None = None
    rows: int
    columns: int


class StoredFile(BaseModel):
    id: str
    filename: str
    extension: str
    size_bytes: int
    uploaded_at: datetime
    tables: list[TableRef]


class Project(BaseModel):
    id: str
    name: str
    created_at: datetime
    files: list[StoredFile] = Field(default_factory=list)


class ProjectNotFoundError(LookupError):
    pass


def _now() -> datetime:
    return datetime.now(timezone.utc)


class ProjectStore:
    def __init__(self, root: Path):
        self.root = Path(root)

    # -- paths -------------------------------------------------------------
    def project_dir(self, project_id: str) -> Path:
        # Ids are generated by us; reject anything that could escape the root.
        if not project_id.isalnum():
            raise ProjectNotFoundError(project_id)
        return self.root / project_id

    def file_path(self, project_id: str, stored: StoredFile) -> Path:
        return self.project_dir(project_id) / "files" / f"{stored.id}{stored.extension}"

    def _manifest(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "project.json"

    def _profile_cache(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "profile.json"

    # -- projects ----------------------------------------------------------
    def create(self, name: str) -> Project:
        project = Project(id=uuid.uuid4().hex, name=name.strip() or "Untitled Project", created_at=_now())
        (self.project_dir(project.id) / "files").mkdir(parents=True, exist_ok=True)
        self.save(project)
        return project

    def get(self, project_id: str) -> Project:
        path = self._manifest(project_id)
        if not path.exists():
            raise ProjectNotFoundError(project_id)
        return Project.model_validate_json(path.read_text(encoding="utf-8"))

    def save(self, project: Project) -> None:
        self._manifest(project.id).write_text(project.model_dump_json(indent=2), encoding="utf-8")
        self.clear_profile(project.id)

    # -- files -------------------------------------------------------------
    def add_file(self, project: Project, stored: StoredFile, content: bytes) -> Project:
        self.file_path(project.id, stored).write_bytes(content)
        project.files.append(stored)
        self.save(project)
        return project

    def remove_file(self, project: Project, file_id: str) -> Project:
        stored = next((f for f in project.files if f.id == file_id), None)
        if stored is None:
            raise ProjectNotFoundError(file_id)
        self.file_path(project.id, stored).unlink(missing_ok=True)
        project.files = [f for f in project.files if f.id != file_id]
        self.save(project)
        return project

    # -- profile cache -----------------------------------------------------
    def read_profile(self, project_id: str) -> dict | None:
        path = self._profile_cache(project_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    def write_profile(self, project_id: str, data: dict) -> None:
        self._profile_cache(project_id).write_text(json.dumps(data, default=str), encoding="utf-8")

    def clear_profile(self, project_id: str) -> None:
        self._profile_cache(project_id).unlink(missing_ok=True)

    # -- cleaning decisions ------------------------------------------------
    def _cleaning(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "cleaning.json"

    def read_cleaning(self, project_id: str) -> dict:
        path = self._cleaning(project_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}

    def write_cleaning(self, project_id: str, data: dict) -> None:
        self._cleaning(project_id).write_text(json.dumps(data, indent=2), encoding="utf-8")

    # -- business context & brand ------------------------------------------
    def _context(self, project_id: str) -> Path:
        return self.project_dir(project_id) / "context.json"

    def read_context(self, project_id: str) -> dict | None:
        path = self._context(project_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    def write_context(self, project_id: str, data: dict) -> None:
        self._context(project_id).write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")

    def logo_path(self, project_id: str, extension: str) -> Path:
        return self.project_dir(project_id) / "brand" / f"logo{extension}"

    def save_logo(self, project_id: str, extension: str, content: bytes) -> None:
        self.remove_logo(project_id)
        path = self.logo_path(project_id, extension)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)

    def remove_logo(self, project_id: str) -> None:
        brand = self.project_dir(project_id) / "brand"
        for old in brand.glob("logo.*") if brand.exists() else []:
            old.unlink()


def new_file_id() -> str:
    return uuid.uuid4().hex[:12]
