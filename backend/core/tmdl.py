"""TMDL files for the semantic model (tables, columns, M partitions, relationships, date table).

Kept separate from modelling.py so the PBIP builder (Module 11) writes the exact same files.
Reference: https://learn.microsoft.com/analysis-services/tmdl/tmdl-overview
"""

from __future__ import annotations

import io
import re
import uuid
import zipfile

from core.cleaning import PipelineResult, m_name, m_text
from core.modelling import DATE_TABLE, ModelColumn, ModelPlan, ModelTable

DATA_FOLDER_DEFAULT = "C:\\DashPilot\\Data\\"
_PLAIN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

DATE_COLUMNS: list[tuple[str, str, str | None]] = [  # name, dataType, sortByColumn
    ("Date", "dateTime", None),
    ("Year", "int64", None),
    ("Quarter", "string", None),
    ("Month Number", "int64", None),
    ("Month Name", "string", "Month Number"),
    ("Year Month", "string", None),
    ("Week of Year", "int64", None),
    ("Day", "int64", None),
    ("Day of Week Number", "int64", None),
    ("Day of Week", "string", "Day of Week Number"),
    ("Fiscal Year", "string", None),
    ("Fiscal Quarter", "string", None),
]


def name(value: str) -> str:
    """TMDL object name, quoted when it is not a plain identifier."""
    return value if _PLAIN.match(value) else "'" + value.replace("'", "''") + "'"


def _tag(*parts: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "dashpilot/" + "/".join(parts)))


def _indent(text: str, tabs: int) -> str:
    return "\n".join("\t" * tabs + line for line in text.splitlines())


def _with_date_keys(m_script: str, derived: list[ModelColumn]) -> str:
    """Append date-only copies of datetime columns so they can join the date table."""
    if not derived:
        return m_script
    head, _, last = m_script.rpartition("\nin\n")
    prev = last.strip()
    steps = []
    for col in derived:
        source = col.name.removesuffix("_date")
        step = m_name(f"Added {col.name}")
        steps.append(
            f"    {step} = Table.AddColumn({prev}, {m_text(col.name)}, "
            f"each DateTime.Date(Record.Field(_, {m_text(source)})), type date)"
        )
        prev = step
    return f"{head},\n" + ",\n".join(steps) + f"\nin\n    {prev}"


def date_table_m(plan: ModelPlan) -> str:
    spec = plan.date_table
    y1, m1, d1 = (int(x) for x in (spec.start or "2020-01-01").split("-"))
    y2, m2, d2 = (int(x) for x in (spec.end or "2020-12-31").split("-"))
    fy = spec.fiscal_year_start_month
    # Fiscal years are named by the calendar year they end in (FY2024 = Apr 2023 - Mar 2024).
    fiscal_year = "Date.Year([Date])" if fy == 1 else f"Date.Year([Date]) + (if Date.Month([Date]) >= {fy} then 1 else 0)"
    return f"""// {DATE_TABLE} - generated by DashPilot
let
    StartDate = #date({y1}, {m1}, {d1}),
    EndDate = #date({y2}, {m2}, {d2}),
    Dates = List.Dates(StartDate, Duration.Days(EndDate - StartDate) + 1, #duration(1, 0, 0, 0)),
    #"As Table" = Table.TransformColumnTypes(Table.FromList(Dates, Splitter.SplitByNothing(), {{"Date"}}), {{{{"Date", type date}}}}),
    #"Year" = Table.AddColumn(#"As Table", "Year", each Date.Year([Date]), Int64.Type),
    #"Quarter" = Table.AddColumn(#"Year", "Quarter", each "Q" & Text.From(Date.QuarterOfYear([Date])), type text),
    #"Month Number" = Table.AddColumn(#"Quarter", "Month Number", each Date.Month([Date]), Int64.Type),
    #"Month Name" = Table.AddColumn(#"Month Number", "Month Name", each Date.MonthName([Date], "en-US"), type text),
    #"Year Month" = Table.AddColumn(#"Month Name", "Year Month", each Date.ToText([Date], "yyyy-MM"), type text),
    #"Week of Year" = Table.AddColumn(#"Year Month", "Week of Year", each Date.WeekOfYear([Date], Day.Monday), Int64.Type),
    #"Day" = Table.AddColumn(#"Week of Year", "Day", each Date.Day([Date]), Int64.Type),
    #"Day of Week Number" = Table.AddColumn(#"Day", "Day of Week Number", each Date.DayOfWeek([Date], Day.Monday) + 1, Int64.Type),
    #"Day of Week" = Table.AddColumn(#"Day of Week Number", "Day of Week", each Date.DayOfWeekName([Date], "en-US"), type text),
    #"Fiscal Year" = Table.AddColumn(#"Day of Week", "Fiscal Year", each "FY" & Text.From({fiscal_year}), type text),
    #"Fiscal Quarter" = Table.AddColumn(#"Fiscal Year", "Fiscal Quarter", each "FQ" & Text.From(Number.IntegerDivide(Number.Mod(Date.Month([Date]) - {fy} + 12, 12), 3) + 1), type text)
in
    #"Fiscal Quarter\""""


def _column(table: str, col: ModelColumn) -> str:
    lines = [f"\tcolumn {name(col.name)}", f"\t\tdataType: {col.data_type}"]
    if col.data_type == "dateTime" and col.detected_type == "date":
        lines.append("\t\tformatString: yyyy-mm-dd")
    if col.hidden:
        lines.append("\t\tisHidden")
    lines.append(f"\t\tlineageTag: {_tag(table, col.name)}")
    lines.append(f"\t\tsummarizeBy: {'sum' if col.measure_candidate else 'none'}")
    lines.append(f"\t\tsourceColumn: {col.name}")
    return "\n".join(lines)


def _table(t: ModelTable, m_script: str) -> str:
    cols = "\n\n".join(_column(t.name, c) for c in t.columns)
    return (
        f"table {name(t.name)}\n\tlineageTag: {_tag(t.name)}\n\n{cols}\n\n"
        f"\tpartition {name(t.name)} = m\n\t\tmode: import\n\t\tsource =\n{_indent(m_script, 4)}\n"
    )


def _date_table(plan: ModelPlan) -> str:
    cols = []
    for col, data_type, sort_by in DATE_COLUMNS:
        lines = [f"\tcolumn {name(col)}", f"\t\tdataType: {data_type}"]
        if col == "Date":
            lines += ["\t\tisKey", "\t\tformatString: yyyy-mm-dd"]
        lines += [f"\t\tlineageTag: {_tag(DATE_TABLE, col)}", "\t\tsummarizeBy: none", f"\t\tsourceColumn: {col}"]
        if sort_by:
            lines.append(f"\t\tsortByColumn: {name(sort_by)}")
        cols.append("\n".join(lines))
    return (
        f"table {DATE_TABLE}\n\tdataCategory: Time\n\tlineageTag: {_tag(DATE_TABLE)}\n\n" + "\n\n".join(cols)
        + f"\n\n\tpartition {DATE_TABLE} = m\n\t\tmode: import\n\t\tsource =\n{_indent(date_table_m(plan), 4)}\n"
    )


def _relationships(plan: ModelPlan) -> str:
    blocks = []
    for r in plan.relationships:
        if not r.valid:
            continue
        lines = [f"relationship {_tag('rel', r.id)}"]
        if not r.active:
            lines.append("\tisActive: false")
        if r.cross_filter == "both":
            lines.append("\tcrossFilteringBehavior: bothDirections")
        if r.cardinality == "one_to_one":
            lines.append("\tfromCardinality: one")
        lines.append(f"\tfromColumn: {name(r.from_table)}.{name(r.from_column)}")
        lines.append(f"\ttoColumn: {name(r.to_table)}.{name(r.to_column)}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"


def model_folder(project_name: str) -> str:
    return (re.sub(r"[^0-9A-Za-z_-]+", "_", project_name).strip("_") or "DashPilot") + ".SemanticModel"


MEASURES_TABLE = "_Measures"


def measures_table(measures) -> str:
    """A measure-only table: one hidden placeholder column, every measure with folder/format/description."""
    blocks = []
    for m in measures:
        lines = [f"\t/// {line}" for line in (m.description or "").splitlines() if line.strip()]
        expression = m.expression.strip()
        if "\n" in expression:
            lines.append(f"\tmeasure {name(m.name)} =")
            lines += ["\t\t\t" + line for line in expression.splitlines()]
        else:
            lines.append(f"\tmeasure {name(m.name)} = {expression}")
        lines.append(f"\t\tformatString: {m.format_string}")
        lines.append(f"\t\tdisplayFolder: {m.folder}")
        lines.append(f"\t\tlineageTag: {_tag(MEASURES_TABLE, m.name)}")
        blocks.append("\n".join(lines))
    body = "\n\n".join(blocks)
    return (
        f"table {MEASURES_TABLE}\n\tlineageTag: {_tag(MEASURES_TABLE)}\n\n{body}\n\n"
        f"\tcolumn Column\n\t\tdataType: string\n\t\tisHidden\n\t\tlineageTag: {_tag(MEASURES_TABLE, 'Column')}\n"
        f"\t\tsummarizeBy: none\n\t\tsourceColumn: Column\n\n"
        f"\tpartition {MEASURES_TABLE} = m\n\t\tmode: import\n\t\tsource = #table(type table [Column = text], {{}})\n"
    )


def build_files(plan: ModelPlan, cleaned: dict[str, PipelineResult], project_name: str, measures=None) -> dict[str, str]:
    """{relative path: content} for the {Project}.SemanticModel folder (included tables only)."""
    root = model_folder(project_name)
    d = f"{root}/definition"
    included = [t for t in plan.tables if t.included]
    refs = [t.name for t in included] + ([DATE_TABLE] if plan.date_table.enabled else []) + ([MEASURES_TABLE] if measures else [])
    files = {
        f"{root}/definition.pbism": '{\n  "version": "4.0",\n  "settings": {}\n}\n',
        f"{d}/database.tmdl": "database\n\tcompatibilityLevel: 1600\n",
        f"{d}/model.tmdl": (
            "model Model\n\tculture: en-US\n\tdefaultPowerBIDataSourceVersion: powerBI_V3\n\tsourceQueryCulture: en-US\n"
            "\tdataAccessOptions\n\t\tlegacyRedirects\n\t\treturnErrorValuesAsNull\n\n"
            + "\n".join(f"ref table {name(r)}" for r in refs) + "\n"
        ),
        f"{d}/expressions.tmdl": (
            f"expression DataFolder = {m_text(DATA_FOLDER_DEFAULT)} meta [IsParameterQuery=true, Type=\"Text\", IsParameterQueryRequired=true]\n"
            f"\tlineageTag: {_tag('DataFolder')}\n"
        ),
        f"{d}/relationships.tmdl": _relationships(plan),
    }
    for t in included:
        m_script = _with_date_keys(cleaned[t.name].m_script, [c for c in t.columns if c.derived])
        files[f"{d}/tables/{t.name}.tmdl"] = _table(t, m_script)
    if plan.date_table.enabled:
        files[f"{d}/tables/{DATE_TABLE}.tmdl"] = _date_table(plan)
    if measures:
        files[f"{d}/tables/{MEASURES_TABLE}.tmdl"] = measures_table(measures)
    return files


def check(plan: ModelPlan) -> list[str]:
    """Structural checks before export: unique names, relationship columns exist, a fact table."""
    errors = []
    included = [t for t in plan.tables if t.included]
    names = [t.name.lower() for t in included] + ([DATE_TABLE.lower()] if plan.date_table.enabled else [])
    if len(names) != len(set(names)):
        errors.append("Two tables have the same name.")
    columns = {t.name: {c.name for c in t.columns} for t in included}
    if plan.date_table.enabled:
        columns[DATE_TABLE] = {c for c, _, _ in DATE_COLUMNS}
    for r in plan.relationships:
        if r.valid and (r.from_column not in columns.get(r.from_table, set()) or r.to_column not in columns.get(r.to_table, set())):
            errors.append(f"Relationship {r.id} points to a missing column.")
    if not any(t.kind == "fact" for t in included):
        errors.append("The model has no fact table.")
    return errors


def zip_files(files: dict[str, str]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, content in files.items():
            zf.writestr(path, content)
    return buf.getvalue()
